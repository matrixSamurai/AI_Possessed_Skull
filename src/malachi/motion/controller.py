from typing import Protocol


class MotionController(Protocol):
    def set_eye_target(self, x: float, y: float) -> None: ...
    def set_jaw_position(self, value: float) -> None: ...
    def set_head_target(self, x: float, y: float) -> None: ...
    def set_led_effect(self, effect: str) -> None: ...
    def neutral_position(self) -> None: ...
    def emergency_stop(self) -> None: ...


def clamp(value, low=-1.0, high=1.0):
    return max(low, min(high, value))
